interface ColorOptionInput {
  name: string;
  hex: string;
  image: string;
}

interface SeedInput {
  id: string;
  brand: SmartphoneBrand;
  name: string;
  price: number;
  originalPrice?: number;
  discountPercent?: number;
  rating: number;
  reviews: string;
  defaultColor: string;
  colorHex: string;
  primaryImg: string;
  secondaryImg: string;
  extraColors?: ColorOptionInput[];
  storageOptions?: string[];
  badgeText?: string;
  isPopular?: boolean;
  isDeal?: boolean;
  stockCount?: number;
  shortDescription: string;
  specs: SmartphoneSpecs;
}

function makePhone(s: SeedInput): SmartphoneModel {
  const storageOptions = s.storageOptions || ['128GB', '256GB', '512GB'];
  const colors = s.extraColors || [
    { name: s.defaultColor, hex: s.colorHex, image: s.primaryImg },
    { name: 'Silver Titanium', hex: '#CBD5E1', image: s.secondaryImg },
    { name: 'Midnight Slate', hex: '#1E293B', image: IMG_SAMSUNG_BLACK },
    { name: 'Champagne Gold', hex: '#C6A67D', image: IMG_DESERT_TITANIUM },
  ];

  return {
    id: s.id,
    brand: s.brand,
    name: s.name,
    storageOptions,
    defaultStorage: storageOptions[0],
    colors,
    defaultColor: s.defaultColor,
    currentPrice: s.price,
    originalPrice: s.originalPrice,
    discountPercent: s.discountPercent,
    rating: s.rating,
    reviewsCountText: s.reviews,
    badgeText: s.badgeText,
    isPopular: s.isPopular,
    isDeal: s.isDeal,
    stockCount: s.stockCount ?? 9,
    shortDescription: s.shortDescription,
    images: [
      { url: s.primaryImg, alt: `${s.name} in ${s.defaultColor} - Front & Rear Studio View`, label: 'Studio View' },
      { url: s.secondaryImg, alt: `${s.name} - Alternate Finish Angle`, label: 'Alternate Finish' },
      { url: colors[2]?.image || IMG_SAMSUNG_BLACK, alt: `${s.name} - Dark Edition`, label: 'Dark Trim' },
      { url: colors[3]?.image || IMG_IPHONE_SILVER_TITANIUM, alt: `${s.name} - Light Edition`, label: 'Signature Finish' },
    ],
    specs: s.specs,
  };
}

